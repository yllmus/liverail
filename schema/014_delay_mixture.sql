-- Store a fitted two-component lognormal mixture alongside the percentiles.
--
-- WHY. schema/012 stores p50/p75/p90/p95 and api.py interpolates between them,
-- holding flat above p95. Backtested against 18,227 real German transfers and
-- 3,642 Polish ones on days the model never saw, that is measurably worse than
-- fitting a mixture:
--
--     model         Brier (DE)   Brier (PL)      lower is better
--     base rate       0.0698       0.0703
--     shipped         0.0403       0.0395
--     mixture         0.0350       0.0377
--
-- and the reliability curve says WHY. The shipped model is pessimistic in
-- every single bin, in both countries - it predicted 0.034 where 0.198 of
-- connections actually worked, and 0.948 where 0.987 did. It tells riders they
-- will miss connections they would have made. Under the mixture most bins land
-- within 0.05.
--
-- The reason is in the literature (arXiv 2504.17479, and the same idea in
-- production at bahnvorhersage.de): train delay is generated by two processes,
-- normal operation and disruption, and no single distribution describes both.
-- One curve fitted to the body has a tail that decays far too fast to
-- represent the disrupted cases - which are exactly the cases that break a
-- connection.
--
-- Percentiles are NOT removed. They are what /distribution reports, they are
-- cheap to compute in SQL, and they are the fallback wherever a cell is too
-- thin to fit a mixture on. This is additive.
--
-- shift exists because delays go negative - trains run early - and log() does
-- not. The series is shifted by its minimum before fitting and shifted back
-- when sampling.

ALTER TABLE delay_distribution
    ADD COLUMN IF NOT EXISTS mix_w1    double precision,
    ADD COLUMN IF NOT EXISTS mix_mu1   double precision,
    ADD COLUMN IF NOT EXISTS mix_sig1  double precision,
    ADD COLUMN IF NOT EXISTS mix_mu2   double precision,
    ADD COLUMN IF NOT EXISTS mix_sig2  double precision,
    ADD COLUMN IF NOT EXISTS mix_shift double precision,
    ADD COLUMN IF NOT EXISTS mix_n     integer;

GRANT ALL ON delay_distribution TO trainuser;
